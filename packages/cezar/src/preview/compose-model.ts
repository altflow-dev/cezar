import { isAbsolute, relative, resolve } from 'node:path';
import type { PreviewConfig } from './config.ts';

/**
 * The slice of `docker compose config --format json` (the normalized, fully merged model)
 * that previews read. Compose normalizes every short syntax into these long forms, so the
 * override and the lint never parse `"8000:8000"` strings themselves.
 */
export interface ComposeService {
  ports?: { target?: number; published?: string | number; host_ip?: string; protocol?: string }[];
  volumes?: { type?: string; source?: string; target?: string }[];
  container_name?: string;
  privileged?: boolean;
  cap_add?: string[];
  network_mode?: string;
  pid?: string;
  ipc?: string;
  userns_mode?: string;
  devices?: unknown[];
}
export interface ComposeModel {
  services?: Record<string, ComposeService>;
}

export interface PlannedPort {
  label: string;
  service: string;
  /** Container port. */
  port: number;
  path: string;
}

/**
 * Which container ports become links. With `expose` in preview.yml: exactly those. Without it
 * (no preview.yml, or one that names no `expose`): every port the compose file publishes, one
 * link each, labelled by service — the zero-config guess. Ports compose only `expose`s to
 * other containers are never published.
 */
export function planPorts(model: ComposeModel, config: PreviewConfig): { ok: true; ports: PlannedPort[] } | { ok: false; error: string } {
  const services = model.services ?? {};
  if (config.expose && Object.keys(config.expose).length) {
    const ports: PlannedPort[] = [];
    for (const [label, e] of Object.entries(config.expose)) {
      if (!services[e.service]) {
        return { ok: false, error: `expose "${label}" names service "${e.service}", which the compose file does not define (${Object.keys(services).join(', ') || 'none'})` };
      }
      ports.push({ label, service: e.service, port: e.port, path: e.path });
    }
    return { ok: true, ports };
  }
  const ports: PlannedPort[] = [];
  for (const [name, svc] of Object.entries(services)) {
    const targets = [...new Set((svc.ports ?? []).map((p) => p.target).filter((t): t is number => typeof t === 'number'))];
    for (const target of targets) ports.push({ label: targets.length > 1 ? `${name}:${target}` : name, service: name, port: target, path: '/' });
  }
  if (!ports.length) {
    return { ok: false, error: 'the compose file publishes no ports and preview.yml names no "expose" — nothing to link to' };
  }
  return { ok: true, ports };
}

const q = (s: string) => JSON.stringify(s);

/**
 * The override compose file that makes one preview coexist with every other one:
 *  - exposed services publish ONLY their allocated host ports (`!override`), on `bind`;
 *  - every other service with published ports publishes none (`!reset []`) — a dev compose that
 *    publishes Postgres on 5456 would otherwise collide with the next task's copy;
 *  - every fixed `container_name` is dropped (`!reset null`), since two stacks cannot share one.
 * Named volumes and networks are already isolated by the `-p` project name. Needs compose 2.24+.
 */
export function renderOverride(
  model: ComposeModel,
  planned: PlannedPort[],
  hostPorts: number[],
  bind: string,
  serviceEnv: Record<string, Record<string, string>> = {},
): string {
  const services = model.services ?? {};
  const bySvc = new Map<string, string[]>();
  planned.forEach((p, i) => {
    const list = bySvc.get(p.service) ?? [];
    list.push(`${bind}:${hostPorts[i]}:${p.port}`);
    bySvc.set(p.service, list);
  });
  const lines = ['# generated by cezar for a task preview — do not edit', 'services:'];
  const names = [...new Set([...Object.keys(services), ...bySvc.keys(), ...Object.keys(serviceEnv)])].sort();
  for (const name of names) {
    const svc = services[name] ?? {};
    const mapped = bySvc.get(name);
    const body: string[] = [];
    if (mapped) {
      body.push('    ports: !override');
      for (const m of mapped) body.push(`      - ${q(m)}`);
    } else if (svc.ports?.length) {
      body.push('    ports: !reset []');
    }
    if (svc.container_name) body.push('    container_name: !reset null');
    const env = serviceEnv[name];
    if (env && Object.keys(env).length) {
      body.push('    environment:');
      for (const [k, v] of Object.entries(env)) body.push(`      ${k}: ${q(v)}`);
    }
    if (!body.length) continue;
    lines.push(`  ${q(name)}:`, ...body);
  }
  if (lines.length === 2) lines[1] = 'services: {}';
  return `${lines.join('\n')}\n`;
}

/**
 * Refuse what would let a compose file reach the host rather than the containers. Docker on a
 * server is root-equivalent and the code under build was written by an agent, so this runs on
 * the final, merged model — after the override — whatever `trustWorktreeConfig` says.
 */
export function lintComposeModel(model: ComposeModel, worktree: string): string[] {
  const issues: string[] = [];
  const root = resolve(worktree);
  const inside = (p: string) => {
    const rel = relative(root, resolve(root, p));
    return rel === '' || (!rel.startsWith('..') && !isAbsolute(rel));
  };
  for (const [name, svc] of Object.entries(model.services ?? {})) {
    const at = `service "${name}"`;
    if (svc.privileged) issues.push(`${at} is privileged`);
    if (svc.cap_add?.length) issues.push(`${at} adds capabilities (${svc.cap_add.join(', ')})`);
    for (const [key, value] of [['network_mode', svc.network_mode], ['pid', svc.pid], ['ipc', svc.ipc], ['userns_mode', svc.userns_mode]] as const) {
      if (value === 'host') issues.push(`${at} uses ${key}: host`);
    }
    if (svc.devices?.length) issues.push(`${at} maps host devices`);
    for (const v of svc.volumes ?? []) {
      if (v.type !== 'bind' || !v.source) continue;
      if (/docker\.sock$/.test(v.source)) issues.push(`${at} mounts the docker socket (${v.source})`);
      else if (!inside(v.source)) issues.push(`${at} bind-mounts ${v.source}, which is outside the task worktree`);
    }
  }
  return issues;
}

/**
 * Fill preview.yml's `serviceEnv` placeholders: `{host}` (the preview's public host),
 * `{port:<label>}` (that exposed label's host port) and `{url:<label>}` (its full URL, path
 * included). Only those three shapes are touched, so other braces in a value survive; a label
 * that is not exposed is an error rather than an empty string baked into the app's config.
 */
export function renderServiceEnv(
  serviceEnv: Record<string, Record<string, string>> | undefined,
  services: Record<string, ComposeService>,
  ports: { label: string; hostPort: number; path: string }[],
  host: string,
): { ok: true; env: Record<string, Record<string, string>> } | { ok: false; error: string } {
  const env: Record<string, Record<string, string>> = {};
  const hostPart = host.includes(':') && !host.startsWith('[') ? `[${host}]` : host;
  for (const [service, vars] of Object.entries(serviceEnv ?? {})) {
    if (!services[service]) return { ok: false, error: `serviceEnv names service "${service}", which the compose file does not define` };
    env[service] = {};
    for (const [key, value] of Object.entries(vars)) {
      let missing: string | undefined;
      const rendered = value.replace(/\{(host|port:([^{}]+)|url:([^{}]+))\}/g, (all, _kind: string, portLabel?: string, urlLabel?: string) => {
        if (all === '{host}') return host;
        const label = (portLabel ?? urlLabel) as string;
        const p = ports.find((x) => x.label === label);
        if (!p) {
          missing = label;
          return all;
        }
        return portLabel ? String(p.hostPort) : `http://${hostPart}:${p.hostPort}${p.path === '/' ? '' : p.path}`;
      });
      if (missing !== undefined) {
        return { ok: false, error: `serviceEnv ${service}.${key} names "${missing}", which is not an exposed label (${ports.map((p) => p.label).join(', ') || 'none'})` };
      }
      env[service][key] = rendered;
    }
  }
  return { ok: true, env };
}
